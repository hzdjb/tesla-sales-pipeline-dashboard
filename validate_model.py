    wp_all = MD.rows("Opportunity", ctx, removed=("Dim_Date",), where=lambda x: x.IsClosed == False).WeightedRevenue.sum()
    won, lost = int((Op.IsWon == True).sum()), int((Op.Stage == "Closed Lost").sum())
    m = {
        "Total Leads": len(Ld), "Converted Leads": int((Ld.Status == "Converted").sum()),
        "Total Opportunities": len(Op), "Closed Won": won, "Closed Lost": lost,
        "Open Opportunities": int((Op.IsClosed == False).sum()),
        "Conversions": cnt("Fact_LeadConversion", ctx),
        "Lead SLA 24h %": div(int(Ld.IsLeadSLA24hMet.sum()), len(Ld)),
        "TD SLA 48h %": sla(Op, "IsTDSLA48hMet"), "FollowUp SLA 7d %": sla(Op, "IsFollowUpSLA7dMet"),
        "LTP SLA 30d %": sla(Op, "IsLTPSLA30dMet"),
        "Total Revenue NZD": float(Wd.ExpectedRevenue.sum()), "Deliveries": len(Wd),
        "Weighted Pipeline": float(Op.loc[Op.IsClosed == False, "WeightedRevenue"].sum()),
        "Open Pipeline NZD": float(Op.loc[Op.IsClosed == False, "ExpectedRevenue"].sum()),
        "Next Quarter Revenue Target": nq_target, "Pipeline Coverage %": div(wp_all, nq_target),
        "Public Pool Leads": int(Ld.IsPublicPool.sum()),
        "Reactivated Pool Leads": int((Ld.IsPublicPool & Ld.IsReactivated).sum()),
        "Pool Leads Converted": int((Ld.IsPublicPool & (Ld.Status == "Converted")).sum()),
        "Public Pool Opps": int(Op.IsPublicPool.sum()), "Reactivated Pool Opps": int((Op.IsPublicPool & Op.IsReactivated).sum()),
        "Stale LTP": int(Op.IsStale.sum()),
        "Activity Count": len(Ac), "Connected Rate": div(int(Ac.IsConnected.sum()), len(Ac)),
        "Positive Outcome Rate": div(int(Ac.IsPositive.sum()), int(Ac.IsConnected.sum())),
        "Leads Target": target(ctx, "Leads"), "Closed Won Target": target(ctx, "ClosedWon"),
        "Revenue Target": target(ctx, "Revenue"),
        "Lead SLA Target": target(ctx, "LeadSLA24h", "mean"), "TD SLA Target": target(ctx, "TDSLA48h", "mean"),
        "FollowUp SLA Target": target(ctx, "FollowUpSLA7d", "mean"), "LTP SLA Target": target(ctx, "LTPSLA30d", "mean"),
        "Charging Attach %": div(MD.rows("Charging", ctx).OpportunityId.nunique(), len(Op)),
        "Trade-in Attach %": div(MD.rows("TradeIn", ctx).OpportunityId.nunique(), len(Op)),
    }
    m["Lead to Opp %"] = div(m["Converted Leads"], m["Total Leads"])
    m["Close Won %"] = div(won, won + lost)
    m["Lead to Won %"] = div(won, m["Total Leads"])
    m["Avg Order NZD"] = div(m["Total Revenue NZD"], m["Deliveries"])
    m["Public Pool Lead %"] = div(m["Public Pool Leads"], m["Total Leads"])
    m["Public Pool Reactivation %"] = div(m["Reactivated Pool Leads"], m["Public Pool Leads"])
    m["Opp Pool Reactivation %"] = div(m["Reactivated Pool Opps"], m["Public Pool Opps"])
    m["Revenue vs Target %"] = div(m["Total Revenue NZD"], m["Revenue Target"])
    m["Leads vs Target %"] = div(m["Total Leads"], m["Leads Target"])
    m["Deliveries vs Target %"] = div(m["Deliveries"], m["Closed Won Target"])
    worst = []
    for k, a, t in [("Lead", "Lead SLA 24h %", "Lead SLA Target"), ("TD", "TD SLA 48h %", "TD SLA Target"),
                    ("FollowUp", "FollowUp SLA 7d %", "FollowUp SLA Target"), ("LTP", "LTP SLA 30d %", "LTP SLA Target")]:
        m[f"{k} SLA Alert"], m[f"{k} SLA vs Target"] = alert(m[a], m[t])
        worst.append(m[f"{k} SLA Alert"])
    known = [w for w in worst if w]
    m["SLA Alert"] = None if not known else ("Red" if "Red" in known else "Yellow" if "Yellow" in known else "Green")
    return m


