"""
tools/validate_model.py
Simulates the Power BI model outside Power BI, so logic errors show up before you build visuals.

What it checks
  A. Power Query typing: applies the column types declared in powerquery/*.m to the CSVs
     and counts cells that would become "Error" in Power Query.
  B. Relationships (dax/relationships.tmdl): key uniqueness on the one-side, orphan keys,
     matching data types, and ambiguous filter paths (Power BI deactivates one of them).
  C. DAX references (dax/measures.dax): every [Measure] and Table[Column] reference resolves,
     parentheses balance.
  D. Measure results: re-implements the measures with Power BI filter propagation
     (single-direction, one-side filters many-side, USERELATIONSHIP, REMOVEFILTERS)
     and prints the numbers each dashboard page should show.

Run:  python tools/validate_model.py      (after python generate_data.py)
Writes docs/model_validation_report.md and output/dashboard_data.json. Exit code 1 on any failure.
"""

