# D. Measure engine with Power BI filter propagation
# ---------------------------------------------------------------------------


class Model:
    def __init__(self, tables, rels):
        self.t, self.rels = tables, rels

    def mask(self, table, ctx, use=(), removed=()):
        """Rows of `table` visible under filter context ctx {table: bool mask}."""
        m = ctx.get(table)
        m = pd.Series(True, index=self.t[table].index) if m is None else m.copy()
        filtered = table in ctx and table not in removed
        if table in removed:
            m[:] = True
        use_pairs = {(u["ft"], u["tt"]) for u in use}
        for r in self.rels:
            if r["ft"] != table:
                continue
            on = (r in use) or (r["active"] and (r["ft"], r["tt"]) not in use_pairs)
            if not on or r["tt"] in removed:
                continue
            up = self.mask(r["tt"], ctx, use, removed)
            if up is None:
                continue
            keys = set(self.t[r["tt"]].loc[up, r["tc"]])
            m &= self.t[table][r["fc"]].isin(keys)
            filtered = True
        return m if filtered else (None if table not in ctx else m)

    def rows(self, table, ctx, use=(), removed=(), where=None):
        m = self.mask(table, ctx, use, removed)
        df = self.t[table] if m is None else self.t[table][m]
        return df if where is None else df[where(df)]


MD = Model(T, RELS)
CLOSE_REL = [r for r in RELS if r["ft"] == "Opportunity" and r["fc"] == "CloseDate"]


def div(a, b):
    return None if not b or b == 0 or pd.isna(b) else a / b


def cnt(t, ctx, where=None, **kw):
    return len(MD.rows(t, ctx, where=where, **kw))


def sla(df, col):
    v = df[col].dropna()
    return div(int(v.sum()), len(v))


def target(ctx, metric, how="sum", **kw):
    d = MD.rows("Dim_Target", ctx, where=lambda x: x.MetricName == metric, **kw).TargetValue
    return (d.sum() if how == "sum" else d.mean()) if len(d) else None


def alert(actual, tgt):
    if actual is None or tgt is None:
        return None, None
    gap = actual - tgt
    return ("Green" if gap >= 0 else "Yellow" if gap >= -0.05 else "Red"), gap


