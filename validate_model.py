def paths(edges, src, dst):
    """Count distinct filter paths src -> dst over directed edges (one-side -> many-side)."""
    out, stack = 0, [(src, {src})]
    while stack:
        node, seen = stack.pop()
        for a, b in edges:
            if a == node and b not in seen:
                if b == dst:
                    out += 1
                else:
                    stack.append((b, seen | {b}))
    return out


def ambiguous(rels):
    edges = sorted({(r["tt"], r["ft"]) for r in rels if r["active"]})
    nodes = sorted({n for e in edges for n in e})
    return [(a, b, paths(edges, a, b)) for a in nodes for b in nodes if a != b and paths(edges, a, b) > 1]


