def fmt(k, v):
    if v is None:
        return "(blank)"
    if isinstance(v, str):
        return v
    if k.endswith("%") or "SLA" in k and ("Target" in k or "vs" in k) or k.endswith("Rate"):
        return f"{v:+.1%}" if "vs Target" in k and "SLA" in k else f"{v:.1%}"
    if "NZD" in k or "Revenue" in k or "Pipeline" in k:
        return f"${v:,.0f}"
    return f"{v:,.0f}"


