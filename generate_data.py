def to_csv_frame(df):
    out = df.copy()
    for c in out.columns:
        s = out[c]
        nonnull = s.dropna()
        if len(nonnull) and nonnull.map(lambda v: isinstance(v, (bool, np.bool_))).all():
            out[c] = s.map(lambda v: "" if pd.isna(v) else ("TRUE" if bool(v) else "FALSE")).astype(object)
        elif len(nonnull) and nonnull.map(lambda v: isinstance(v, date)).all():
            out[c] = s.map(lambda v: "" if pd.isna(v) else v.isoformat())
    return out


