dim_rep = pd.DataFrame(reps)
dim_rep["TenureMonths"] = [months_between(h, l if l else SNAPSHOT) for h, l in zip(dim_rep.HireDate, dim_rep.LeaveDate)]
dim_rep["IsActive"] = dim_rep["LeaveDate"].isna()
dim_rep = dim_rep[["SalesRepId", "RepName", "StoreId", "Role", "HireDate", "LeaveDate",
                   "TenureMonths", "ManagerName", "IsActive"]]

# Rep "quality" drives SLA performance: longer tenure -> better, plus noise. Range roughly -1..1
rep_quality = {}
for r in dim_rep.itertuples():
    q = np.clip((r.TenureMonths - 24) / 30, -1, 1) * 0.7 + rng.normal(0, 0.3)
    rep_quality[r.SalesRepId] = float(np.clip(q, -1, 1))
rep_info = {r.SalesRepId: (r.StoreId, r.HireDate, r.LeaveDate) for r in dim_rep.itertuples()}
advisors_by_store = {
    sid: [r.SalesRepId for r in dim_rep.itertuples() if r.StoreId == sid and r.Role != "Store Manager"]
    for sid in store_ids
}


def active(rep_id, on):
    _, hire, leave = rep_info[rep_id]
    return hire <= on and (leave is None or on <= leave)


def pick_rep(store, on, also_active_on=None, exclude=None):
    """Random advisor in `store` active on `on` (and still active on `also_active_on`)."""
    cands = [r for r in advisors_by_store[store]
             if active(r, on) and (also_active_on is None or active(r, also_active_on)) and r != exclude]
    return cands[rng.integers(0, len(cands))] if cands else None


